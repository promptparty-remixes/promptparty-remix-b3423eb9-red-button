export function DotMatrixCounter({ value, digits = 4 }: DotMatrixCounterProps) {
  const padded = useMemo(() => {
    const str = Math.max(0, Math.floor(value)).toString();
    return str.padStart(digits, "0");
  }, [value, digits]);

  return (
    <div
      className="flex items-center gap-2 rounded-lg border border-red-900/40 bg-black/70 px-4 py-3 shadow-[0_0_24px_rgba(239,68,68,0.18)]"
      role="status"
      aria-label={`Press count: ${value}`}
    >
      {padded.split("").map((digit, idx) => (
        <Digit key={idx} digit={digit} />
      ))}
    </div>
  );
}

function Digit({ digit }: { digit: string }) {
  const pattern = DIGIT_PATTERNS[digit] ?? DIGIT_PATTERNS["0"];
  return (
    <div className="grid grid-cols-5 gap-[3px]">
      {pattern.flatMap((row, rIdx) =>
        row.map((cell, cIdx) => (
          <span
            key={`${rIdx}-${cIdx}`}
            className={
              cell
                ? "block size-1.5 rounded-full bg-red-500 shadow-[0_0_6px_rgba(239,68,68,0.85)] sm:size-2"
                : "block size-1.5 rounded-full bg-red-950/60 sm:size-2"
            }
          />
        )),
      )}
    </div>
  );
}
